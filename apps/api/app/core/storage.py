"""Object storage for attachments, selected by environment.

Two backends: the local filesystem (development, single-server installs)
and any S3-compatible service. Objects are always private; there is no
public-bucket or public-URL assumption. Keys are generated by the server
(never from user input) and validated before every filesystem access.
"""

from __future__ import annotations

import os
import re
import tempfile
from functools import lru_cache
from pathlib import Path
from typing import TYPE_CHECKING, Any, Protocol

from app.core.config import get_settings

if TYPE_CHECKING:
    from app.core.config import Settings

KEY_PATTERN = re.compile(r"^[a-z0-9_-]+(?:/[a-z0-9_-]+)*\.[a-z0-9]{2,5}$")


class StorageError(Exception):
    pass


def check_key(key: str) -> str:
    if not KEY_PATTERN.fullmatch(key) or ".." in key:
        raise StorageError("invalid storage key")
    return key


class Storage(Protocol):
    name: str

    def put(self, key: str, data: bytes, content_type: str) -> None: ...

    def get(self, key: str) -> bytes: ...

    def delete(self, key: str) -> None: ...


class LocalStorage:
    name = "local"

    def __init__(self, root: str | Path) -> None:
        self.root = Path(root).resolve()

    def _path(self, key: str) -> Path:
        path = (self.root / check_key(key)).resolve()
        if self.root not in path.parents:
            raise StorageError("key escapes the storage root")
        return path

    def put(self, key: str, data: bytes, content_type: str) -> None:
        path = self._path(key)
        path.parent.mkdir(parents=True, exist_ok=True, mode=0o700)
        # Write-then-rename so a crash never leaves a half-written object.
        fd, tmp = tempfile.mkstemp(dir=path.parent, prefix=".upload-")
        try:
            with os.fdopen(fd, "wb") as fh:
                fh.write(data)
            os.chmod(tmp, 0o600)
            os.replace(tmp, path)
        except BaseException:
            Path(tmp).unlink(missing_ok=True)
            raise

    def get(self, key: str) -> bytes:
        try:
            return self._path(key).read_bytes()
        except FileNotFoundError as exc:
            raise StorageError("object not found") from exc

    def delete(self, key: str) -> None:
        self._path(key).unlink(missing_ok=True)


class S3Storage:
    name = "s3"

    def __init__(self, bucket: str, client: Any, prefix: str = "") -> None:
        self.bucket = bucket
        self.client = client
        self.prefix = prefix.strip("/") + "/" if prefix.strip("/") else ""

    def _key(self, key: str) -> str:
        return self.prefix + check_key(key)

    def put(self, key: str, data: bytes, content_type: str) -> None:
        # No ACL argument: objects inherit the bucket's private default.
        self.client.put_object(
            Bucket=self.bucket, Key=self._key(key), Body=data, ContentType=content_type
        )

    def get(self, key: str) -> bytes:
        try:
            response = self.client.get_object(Bucket=self.bucket, Key=self._key(key))
        except self.client.exceptions.NoSuchKey as exc:
            raise StorageError("object not found") from exc
        body: bytes = response["Body"].read()
        return body

    def delete(self, key: str) -> None:
        self.client.delete_object(Bucket=self.bucket, Key=self._key(key))


def build_storage(settings: Settings) -> Storage:
    if settings.storage_backend == "s3":
        if not settings.storage_s3_bucket:
            raise StorageError("STORAGE_S3_BUCKET is required for the s3 backend")
        import boto3  # noqa: PLC0415 - only needed when S3 is configured

        secret = settings.storage_s3_secret_access_key
        client = boto3.client(
            "s3",
            region_name=settings.storage_s3_region,
            endpoint_url=settings.storage_s3_endpoint_url,
            aws_access_key_id=settings.storage_s3_access_key_id,
            aws_secret_access_key=secret.get_secret_value() if secret else None,
        )
        return S3Storage(settings.storage_s3_bucket, client, settings.storage_s3_prefix)
    return LocalStorage(settings.storage_local_root)


@lru_cache
def get_storage() -> Storage:
    return build_storage(get_settings())


# --- Content type detection ------------------------------------------------------

ALLOWED_TYPES = {
    "image/jpeg": ".jpg",
    "image/png": ".png",
    "image/webp": ".webp",
    "application/pdf": ".pdf",
}


def sniff_content_type(data: bytes) -> str | None:
    """Real file type from magic bytes; the client's declared type is ignored."""
    if data.startswith(b"\xff\xd8\xff"):
        return "image/jpeg"
    if data.startswith(b"\x89PNG\r\n\x1a\n"):
        return "image/png"
    if len(data) >= 12 and data[:4] == b"RIFF" and data[8:12] == b"WEBP":
        return "image/webp"
    if data.startswith(b"%PDF-"):
        return "application/pdf"
    return None
